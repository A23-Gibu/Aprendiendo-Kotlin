package Contenido_1_4_Lambda

fun main() {
    val dato1 = 20
    val dato2 = 10
    var resultado: Int

    /*
     * Operaciones aritméticas
     */
    // Suma
    resultado = dato1 + dato2
    println("$dato1 + $dato2 = $resultado")

    // Resta
    resultado = dato1 - dato2
    println("$dato1 - $dato2 = $resultado")

    // Producto
    resultado = dato1 * dato2
    println("$dato1 * $dato2 = $resultado")

    // Cociente
    resultado = dato1 / dato2
    println("$dato1 / $dato2 = $resultado")
}